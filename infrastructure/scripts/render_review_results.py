"""Generate docs/data/source-review-results-v1.md from the catalog.

Mission 1.3 §47. Generated rather than hand-written for the reason ADR-009 gives
about contracts: two hand-maintained copies of one fact drift, and the drift is
found by whoever trusted the wrong one. This one is a DIFF view -- what each
verdict was, what it is now, and on what document -- which the rendered catalog
does not show.
"""

import pathlib
import sys

sys.path.insert(0, "services/acquisition/python")
from sros_acquisition.registry import evaluate_eligibility, load_catalog, resolve_retention
from sros_acquisition.registry.models import LEGACY_USE_PROFILE

catalog = load_catalog("docs/data/source-catalog-v1.json")
L: list[str] = []
add = L.append

by_state: dict[str, list[str]] = {}
changed: list[tuple[str, str, str]] = []
for s in catalog:
    prev, cur = s.review_history[0], s.review
    by_state.setdefault(cur.approval_state.value, []).append(s.source_id)
    if prev.approval_state is not cur.approval_state:
        changed.append((s.source_id, prev.approval_state.value, cur.approval_state.value))

add("# Source review results")
add("")
add("**Status:** Generated. Do not edit by hand.")
add("**Generated by:** `python infrastructure/scripts/render_review_results.py`")
add(
    f"**Catalog version:** {catalog.catalog_version} · reviewed {catalog.review_date} "
    f"by `{catalog.reviewer}`"
)
add("**Governed by:** [`source-registry-v1.md`](source-registry-v1.md)")
add("**Full detail per source:** [`source-catalog-v1.md`](source-catalog-v1.md)")
add("")
add("> This is the **diff**: what each verdict was at a source's FIRST review, what")
add("> it is now, and which document moved it. The rendered catalog carries the full")
add("> assessment.")
add("")
add("---")
add("")
add("## The assessed use case")
add("")
add(f"> {catalog.assessed_use_case}")
add("")
add("Unchanged from Mission 1.0, deliberately. Narrowing the use case would have made")
add("approvals easier and the approvals meaningless.")
add("")
add("## Outcome")
add("")
add("| State | Count | Sources |")
add("|---|---|---|")
for state in (
    "APPROVED",
    "APPROVED_WITH_CONDITIONS",
    "RESTRICTED",
    "REQUIRES_REVIEW",
    "PROHIBITED",
    "SUSPENDED",
    "DRAFT",
):
    ids = by_state.get(state, [])
    add(f"| `{state}` | {len(ids)} | {', '.join(f'`{i}`' for i in ids) if ids else '—'} |")
add("")
eligible = [s.source_id for s in catalog if evaluate_eligibility(s, LEGACY_USE_PROFILE).eligible]
add(f"**Collector-eligible: {len(eligible)} of {len(list(catalog))}.**")
add("")
approving = len(by_state.get("APPROVED", [])) + len(by_state.get("APPROVED_WITH_CONDITIONS", []))
add(
    f"{approving} sources are in an approving state and {len(eligible)} are "
    "collector-eligible. That is not a contradiction: `APPROVED_WITH_CONDITIONS` says a"
)
add("collector MAY be designed, and a source becomes eligible only once every condition")
add("it carries is satisfied by a verifier. Conditions naming a capability nobody has")
add("built yet stay UNKNOWN, and UNKNOWN blocks exactly as a failure does.")
add("")
add("## What changed since each source's first review")
add("")
if changed:
    add("| Source | First review | Current | Direction |")
    add("|---|---|---|---|")
    order = {
        "PROHIBITED": 0,
        "RESTRICTED": 1,
        "REQUIRES_REVIEW": 2,
        "APPROVED_WITH_CONDITIONS": 3,
        "APPROVED": 4,
    }
    for sid, before, after in changed:
        arrow = "raised" if order[after] > order[before] else "**lowered**"
        add(f"| `{sid}` | `{before}` | `{after}` | {arrow} |")
add("")
order_ = {
    "PROHIBITED": 0,
    "RESTRICTED": 1,
    "REQUIRES_REVIEW": 2,
    "APPROVED_WITH_CONDITIONS": 3,
    "APPROVED": 4,
}
lowered = [c for c in changed if order_[c[2]] < order_[c[1]]]
raised = [c for c in changed if order_[c[2]] > order_[c[1]]]
total_ = len(list(catalog))
add(
    f"{len(changed)} of {total_} verdicts changed: {len(raised)} raised, "
    f"**{len(lowered)} lowered**."
)
add("")
if lowered:
    add("Verdicts moving DOWN on current evidence is the clearest sign the review was not")
    add("optimising for approvals. " + ", ".join(f"`{c[0]}`" for c in lowered) + " each")
    add("turned out to have a published policy that excludes this use case rather than one")
    add("that permits it.")
    add("")

# Who was actually looked at in the round this catalog records, as opposed to
# carried forward. Stating "every source was re-reviewed" when twelve were not
# is the drift a generated document exists to prevent.
this_round = [s.source_id for s in catalog if s.review and s.review.reviewed_by == catalog.reviewer]
# "of those" means OF THIS ROUND, so the intersection is what the sentence
# claims. Counting first reviews across the whole catalog produced arithmetic
# nobody could believe -- Mission 1.8 rendered "4 of 27 ... 10 of those are first
# reviews", and Mission 1.9.2, which re-reviewed a single source, rendered
# "1 of 27 ... 10 of those". A generated document exists to stop drift, and it
# cannot do that while stating something impossible.
first_time = [
    s.source_id for s in catalog if s.source_id in this_round and len(s.review_history) <= 1
]
carried = [s.source_id for s in catalog if s.source_id not in this_round]
sentence = f"**{len(this_round)} of {total_} sources carry a review from `{catalog.reviewer}`**"
if first_time:
    sentence += f"; {len(first_time)} of those are first reviews of a new candidate."
else:
    sentence += ", and none of them is a new candidate: every one was already registered."
add(sentence)
if carried:
    add("")
    add(
        f"The remaining {len(carried)} carry a verdict from an earlier round, unchanged and "
        "not re-examined here: " + ", ".join(f"`{s}`" for s in carried) + "."
    )
    add("A verdict that was not revisited is not a verdict that was reconfirmed, and the")
    add("two are kept distinct — its `next_review_at` is what decides when it goes stale.")
add("")
add("---")
add("")
add("## Per-source results")
add("")

for s in catalog:
    prev, cur = s.review_history[0], s.review
    result = evaluate_eligibility(s, LEGACY_USE_PROFILE)
    retention = resolve_retention(s.retention_override)
    add(f"### {s.canonical_name} — `{s.source_id}`")
    add("")
    add("| | |")
    add("|---|---|")
    add(
        f"| Previous status | `{prev.approval_state.value}` (review version {prev.review_version}) |"
    )
    add(f"| **New status** | **`{cur.approval_state.value}`** |")
    add(f"| Collector-eligible | {'yes' if result.eligible else '**no**'} |")
    add(
        f"| Review version | {cur.review_version}, reviewed {cur.reviewed_at.date()}, "
        f"next due {cur.next_review_at.date()} |"
    )
    add(
        f"| Retention if collected | raw {retention.raw_days}d, "
        f"normalized {retention.normalized_days}d ({retention.raw_source}) |"
    )
    add(f"| Attribution | {cur.assessment('attribution_required').value} |")
    add(
        f"| Personal-data risk | `{cur.personal_data_risk.value}`"
        f"{' · user-generated content' if cur.contains_user_generated_content else ''}"
        f"{' · user identifiers' if cur.contains_user_identifiers else ''} |"
    )
    add("")
    add("**Documents reviewed**")
    add("")
    if cur.evidence:
        for e in cur.evidence:
            add(
                f"- [{e.document_title}]({e.document_url}) — `{e.document_type.value}`, "
                f"retrieved {e.retrieved_at.date()}"
                + (f", section: {e.section_reference}" if e.section_reference else "")
            )
    else:
        add("- None retrievable this mission. See the open questions below.")
    add("")
    add("**Finding**")
    add("")
    add(cur.review_notes or "—")
    add("")
    if cur.evidence:
        add("**What the documents say**")
        add("")
        for e in cur.evidence:
            add(f"> {e.summarized_finding}")
            add("")
    if cur.conditions:
        add("**Conditions**")
        add("")
        for c in cur.conditions:
            add(f"- {c}")
        add("")
    if cur.required_conditions:
        add("**Machine-checkable conditions** — all unsatisfied")
        add("")
        add("| Key | Verified by | Checks |")
        add("|---|---|---|")
        for c in cur.required_conditions:
            detail = f"`{c.verification_detail}`" if c.verification_detail else "—"
            add(f"| `{c.key}` | `{c.verification.value}` | {detail} |")
        add("")
    if cur.open_questions:
        add("**Open questions / next action**")
        add("")
        for q in cur.open_questions:
            add(f"- {q}")
        add("")
    if result.blocking_reasons:
        add("**Blocked by**")
        add("")
        for r in result.blocking_reasons:
            add(f"- {r}")
        add("")
    add("---")
    add("")

add("## Limitations of this review")
add("")
for limitation in catalog.known_limitations:
    add(f"- {limitation}")
add("")

out = pathlib.Path("docs/data/source-review-results-v1.md")
text = "\n".join(L).rstrip("\n") + "\n"
if "--check" in sys.argv:
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        print(f"stale    {out} does not match the catalog. Regenerate.", file=sys.stderr)
        raise SystemExit(1)
    print(f"ok       {out} matches the catalog")
else:
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote    {out}")
